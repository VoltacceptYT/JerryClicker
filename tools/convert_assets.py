#!/usr/bin/env python3
"""Regenerates source/sprites.c, source/sprites.h and icon.bmp from assets/.
Needs Pillow. The generated files are committed, so CI does not run this."""
import os, struct
from collections import Counter
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "assets")

# Must match the order of UPGRADES[] in source/game.c
UPGRADE_IDS = [
    "inflatable_jerry", "jerry_box_green", "jerry_box_blue", "jerry_box_purple",
    "jerry_box_golden", "jerry_box_mega", "jerry_staff", "jerry_rune", "jerry_rune_2",
    "jerry_rune_3", "jerry_talisman_green", "jerry_talisman_blue", "jerry_talisman_purple",
    "jerry_talisman_golden", "jerry_stone", "aspect_of_the_jerry",
    "aspect_of_the_jerry_signature", "pet_item_toy_jerry", "pet_item_lord_jerry",
    "pet_item_scuba_jerry", "pet_item_angel_jerry", "pet_item_iron_jerry",
]
JERRIES = ["jerry", "lord_jerry", "scuba_jerry", "iron_jerry", "angel_jerry"]


def load(path):
    return Image.open(path).convert("RGBA")


def halve(im):
    """32x32 -> 16x16 keeping existing colours only."""
    out = Image.new("RGBA", (im.width // 2, im.height // 2), (0, 0, 0, 0))
    for y in range(out.height):
        for x in range(out.width):
            px = [im.getpixel((2 * x + dx, 2 * y + dy)) for dx in (0, 1) for dy in (0, 1)]
            px = [p for p in px if p[3] >= 128]
            if px:
                out.putpixel((x, y), Counter(px).most_common(1)[0][0])
    return out


def scale(im, f):
    return im.resize((im.width * f, im.height * f), Image.NEAREST)


def rgb15(c):
    return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)


def build_palette(images):
    cols = []
    for im in images:
        for p in im.getdata():
            if p[3] >= 128 and p[:3] not in cols:
                cols.append(p[:3])
    assert len(cols) <= 255, "too many colours: %d" % len(cols)
    return cols


def tiles(im, pal):
    w, h = im.size
    data = bytearray()
    for ty in range(h // 8):
        for tx in range(w // 8):
            for y in range(8):
                for x in range(8):
                    p = im.getpixel((tx * 8 + x, ty * 8 + y))
                    data.append(0 if p[3] < 128 else pal.index(p[:3]) + 1)
    return bytes(data)


def carray(name, data, ctype="unsigned char", dims=""):
    s = "const %s %s%s __attribute__((aligned(4))) = {" % (ctype, name, dims)
    return s


def emit_bytes(b):
    lines = []
    for i in range(0, len(b), 24):
        lines.append("    " + ",".join(str(v) for v in b[i:i + 24]) + ",")
    return "\n".join(lines)


def main():
    icons = []
    for i in UPGRADE_IDS:
        im = load(os.path.join(A, "upgrades", i + ".png"))
        if im.size == (32, 32):
            im = halve(im)
        assert im.size == (16, 16), i
        icons.append(im)
    candy = load(os.path.join(A, "upgrades", "jerry_candy.png"))
    jerries = [scale(load(os.path.join(A, "cosmetics", j + ".png")), 4) for j in JERRIES]
    golden = scale(load(os.path.join(A, "cosmetics", "golden_jerry.png")), 2)

    top_cols = build_palette(icons)
    bot_cols = build_palette(jerries + [golden, candy])

    def pal_words(cols):
        w = [0] + [rgb15(c) for c in cols]
        return w + [0] * (256 - len(w))

    out = ["// GENERATED by tools/convert_assets.py - do not edit.",
           '#include "sprites.h"', ""]
    out.append("const unsigned short top_pal[256] __attribute__((aligned(4))) = {%s};" %
               ",".join(str(v) for v in pal_words(top_cols)))
    out.append("const unsigned short bottom_pal[256] __attribute__((aligned(4))) = {%s};" %
               ",".join(str(v) for v in pal_words(bot_cols)))
    out.append("")
    out.append("const unsigned char icon_gfx[%d][256] __attribute__((aligned(4))) = {" % len(icons))
    for im in icons:
        out.append("  {\n" + emit_bytes(tiles(im, top_cols)) + "\n  },")
    out.append("};")
    out.append("const unsigned char jerry_gfx[%d][4096] __attribute__((aligned(4))) = {" % len(jerries))
    for im in jerries:
        out.append("  {\n" + emit_bytes(tiles(im, bot_cols)) + "\n  },")
    out.append("};")
    out.append("const unsigned char golden_gfx[1024] __attribute__((aligned(4))) = {\n" +
               emit_bytes(tiles(golden, bot_cols)) + "\n};")
    out.append("const unsigned char candy_gfx[256] __attribute__((aligned(4))) = {\n" +
               emit_bytes(tiles(candy, bot_cols)) + "\n};")
    open(os.path.join(ROOT, "source", "sprites.c"), "w").write("\n".join(out) + "\n")

    open(os.path.join(ROOT, "source", "sprites.h"), "w").write(
        "// GENERATED by tools/convert_assets.py\n#ifndef SPRITES_H\n#define SPRITES_H\n"
        "#define ICON_COUNT %d\n#define JERRY_COUNT %d\n"
        "extern const unsigned short top_pal[256];\nextern const unsigned short bottom_pal[256];\n"
        "extern const unsigned char icon_gfx[ICON_COUNT][256];   /* 16x16 8bpp */\n"
        "extern const unsigned char jerry_gfx[JERRY_COUNT][4096]; /* 64x64 8bpp: base, lord, scuba, iron, angel */\n"
        "extern const unsigned char golden_gfx[1024];             /* 32x32 8bpp */\n"
        "extern const unsigned char candy_gfx[256];               /* 16x16 8bpp */\n#endif\n"
        % (len(icons), len(jerries)))

    # 32x32 4bpp icon for the ROM banner
    base = scale(load(os.path.join(A, "cosmetics", "jerry.png")), 2)
    cols = build_palette([base])
    assert len(cols) <= 15
    palette = [(255, 0, 255)] + cols
    palette += [(0, 0, 0)] * (16 - len(palette))
    rows = []
    for y in range(31, -1, -1):
        row = bytearray()
        for x in range(0, 32, 2):
            v = []
            for xx in (x, x + 1):
                p = base.getpixel((xx, y))
                v.append(0 if p[3] < 128 else cols.index(p[:3]) + 1)
            row.append((v[0] << 4) | v[1])
        rows.append(bytes(row))
    pix = b"".join(rows)
    pal = b"".join(struct.pack("BBBB", c[2], c[1], c[0], 0) for c in palette)
    off = 14 + 40 + len(pal)
    hdr = b"BM" + struct.pack("<IHHI", off + len(pix), 0, 0, off)
    dib = struct.pack("<IiiHHIIiiII", 40, 32, 32, 1, 4, 0, len(pix), 2835, 2835, 16, 16)
    open(os.path.join(ROOT, "icon.bmp"), "wb").write(hdr + dib + pal + pix)
    print("top colours", len(top_cols), "bottom colours", len(bot_cols))


main()
